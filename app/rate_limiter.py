"""Minimal in-memory sliding-window rate limiter (per client key, e.g. IP).

NOTE: in-memory means limits reset if the process restarts, and won't be
shared across multiple server workers/instances. For multi-instance
deployments, swap this for a Redis-backed limiter.
"""
import time
from collections import defaultdict, deque


class RateLimiter:
    def __init__(self, max_requests: int, window_seconds: int):
        self.max_requests = max_requests
        self.window_seconds = window_seconds
        self._hits: dict[str, deque] = defaultdict(deque)

    def allow(self, key: str) -> bool:
        now = time.monotonic()
        q = self._hits[key]
        while q and now - q[0] > self.window_seconds:
            q.popleft()
        if len(q) >= self.max_requests:
            return False
        q.append(now)
        return True
